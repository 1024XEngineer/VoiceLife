#include "ssd1306_glyphs.h"

#include <algorithm>
#include <array>
#include <cassert>
#include <string_view>

#include "ssd1306_glyph_assets.h"

int main() {
    using voicelife::display_esp::internal::LookupAsciiGlyph;
    using voicelife::display_esp::internal::LookupBuiltinMoodGlyph;
    using voicelife::display_esp::internal::LookupFallbackGlyph16;
    using voicelife::display_esp::internal::LookupGlyph16;
    using voicelife::display_esp::internal::LookupMoodGlyph;

    for (const char value : std::string_view{"!ABCDEGIKLNORSTWVY0123456789-:/ "}) {
        (void)LookupAsciiGlyph(value);
    }
    assert((LookupAsciiGlyph('A') == std::array<uint8_t, 5>{0x7e, 0x11, 0x11, 0x7e, 0x00}));
    assert((LookupAsciiGlyph('?') == std::array<uint8_t, 5>{0x00, 0x00, 0x00, 0x00, 0x00}));

    constexpr std::array<uint8_t, 32> kUnknownGlyph = {
        0x00, 0xff, 0x81, 0x81, 0x81, 0x81, 0x81, 0x81, 0x81, 0x81, 0x81, 0x81, 0x81, 0x81, 0xff, 0x00,
        0x00, 0xff, 0x81, 0x81, 0x81, 0x81, 0x81, 0x81, 0x81, 0x81, 0x81, 0x81, 0x81, 0x81, 0xff, 0x00,
    };
    assert(LookupGlyph16(0x10ffff) == kUnknownGlyph);

    constexpr std::array<uint32_t, 132> kFallbackCodepoints = {
        0x7a7a, 0x95f2, 0x8046, 0x542c, 0x601d, 0x8003, 0x64ad, 0x62a5, 0x505c, 0x6b62, 0x91cd, 0x8fde, 0x9519, 0x8bef,
        0x5f00, 0x673a, 0x8054, 0x7f51, 0x6536, 0x5230, 0x725b, 0x8d70, 0x4e86, 0x65f6, 0x95f4, 0x4f1a, 0x8bae, 0x521b,
        0x5efa, 0x63d0, 0x9192, 0x8bb0, 0x4e8b, 0x4eca, 0x5929, 0x660e, 0x4e0a, 0x5348, 0x4e0b, 0x70b9, 0x534a, 0x59cb,
        0x7ed3, 0x675f, 0x8bbe, 0x7f6e, 0x67e5, 0x8be2, 0x5217, 0x8868, 0x6dfb, 0x52a0, 0x5220, 0x9664, 0x5b8c, 0x6210,
        0x4fee, 0x6539, 0x5171, 0x6761, 0x4e2a, 0x63a5, 0x4e2d, 0x5904, 0x7406, 0x8bf4, 0x8bdd, 0x51fa, 0x97f3, 0x4f60,
        0x5728, 0x5e72, 0x4ec0, 0x4e48, 0x518d, 0x89c1, 0x62dc, 0x597d, 0x7684, 0x53ef, 0x4ee5, 0x5e2e, 0x6211, 0x505a,
        0x60f3, 0x89c9, 0x5f97, 0x5f88, 0x77e5, 0x9053, 0x73b0, 0x6628, 0x795d, 0x4e00, 0x5207, 0x987a, 0x5229, 0x5f85,
        0x547d, 0x968f, 0x51c6, 0x5907, 0x4e3a, 0x670d, 0x52a1, 0x5173, 0x65e5, 0x7a0b, 0x5f55, 0x5367, 0x69fd, 0x6770,
        0x4f53, 0x98d8, 0x5f39, 0x5934, 0x88c5, 0x903c, 0x64cd, 0x8d5e, 0x7f8e, 0x80a5, 0x54ce, 0x8e6d, 0x724c, 0x98de,
        0x613f, 0x6696, 0x5149, 0x73cd, 0x8d35, 0x8c22,
    };
    for (const uint32_t codepoint : kFallbackCodepoints) {
        const auto glyph = LookupFallbackGlyph16(codepoint);
        assert(std::any_of(glyph.begin(), glyph.end(), [](uint8_t byte) { return byte != 0; }));
    }

    constexpr std::array<uint8_t, 32> kHappyGlyph = {
        0x80, 0x64, 0xcb, 0xcf, 0x7f, 0x60, 0xe0, 0xe0, 0xe0, 0xe0, 0xe0, 0x60, 0x7f, 0xcc, 0xcf, 0x67,
        0x03, 0x1f, 0x7f, 0x7e, 0xff, 0xdf, 0x9e, 0x1f, 0x1f, 0x1f, 0x9e, 0xdf, 0xff, 0x7e, 0x7f, 0x1f,
    };
    assert(LookupMoodGlyph("happy") == kHappyGlyph);
    for (const auto mood : {"happy", "sad", "thinking", "surprised", "speaking", "angry", "neutral"}) {
        assert(LookupMoodGlyph(mood) == LookupBuiltinMoodGlyph(mood));
    }
    assert(LookupMoodGlyph("unknown") == LookupMoodGlyph("neutral"));
}
